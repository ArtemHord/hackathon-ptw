"""Eval of the MSP incident demo: backend/seed/msp/eval.json through the in-call answer path.

Usage: cd backend && uv run python ../scripts/eval_msp.py [--only T3,T7] [--out PATH]
In-process, no call, nothing spoken: profile forced to msp (memory only, the DB setting is not
touched), brief = the INC-024 ticket, empty transcript, AGENT_TOOLS on. Each question goes
through orchestrator.answer_question (same prompt, tools and fallback as a live "Atlas, ...").
Experts come from seed/msp/experts.json (DATABASE_URL is ignored), so no DB is needed.
Scoring per case: every keyword group hit in the answer, no must_not phrase, for answer/safety
at least one expected source ID in the answer or the tool citations, and no escalation.
Prints a table and writes docs/EVAL_MSP.md. Needs OPENAI_API_KEY + OPENAI_CHAT_MODEL.
"""

import argparse
import asyncio
import json
import os
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
os.environ["DATABASE_URL"] = ""  # read-only eval: experts from the msp seed file, no DB

from app import orchestrator, profile, runtime  # noqa: E402
from app.config import get_settings  # noqa: E402

EVAL = ROOT / "backend" / "seed" / "msp" / "eval.json"
OUT = ROOT / "docs" / "EVAL_MSP.md"


def _norm(text: str) -> str:
    return (text or "").replace("\u2019", "'").replace("\u2018", "'").lower()


def keyword_hit(keyword: str, text: str) -> bool:
    """Word-start match ("approv" hits "approval"); 1-2 letter keywords ("no") whole word only,
    so "no" does not hit "NovaStore"."""
    kw = _norm(keyword).strip()
    if not kw:
        return True
    tail = r"(?![\w'])" if len(kw) <= 2 else ""
    return re.search(rf"(?<![\w']){re.escape(kw)}{tail}", _norm(text)) is not None


def score(case: dict, result: dict, meta: dict) -> list[str]:
    answer = result["answer"]
    fails: list[str] = []
    for group in case.get("keywords") or []:
        if not any(keyword_hit(k, answer) for k in group):
            fails.append(f"missing one of {group}")
    for bad in case.get("must_not") or []:
        if _norm(bad) in _norm(answer):
            fails.append(f"says {bad!r}")
    sources = case.get("expected_sources") or []
    if case.get("kind") in ("answer", "safety") and sources:
        hay = _norm(answer + " " + " ".join(meta.get("refs") or []))
        if not any(_norm(s) in hay for s in sources):
            fails.append(f"no source of {sources}")
    if orchestrator.is_escalated(result) and not case.get("expect_escalation"):
        fails.append(f"escalated (topic {result['topic']!r}, conf {result['confidence']:.2f})")
    return fails


async def run_case(case: dict, brief: str) -> dict:
    t0 = time.monotonic()
    try:
        result, meta = await orchestrator.answer_question(
            case["question"], meeting_id=f"eval-{case['id']}", brief=brief, speaker="Kamil"
        )
        fails = score(case, result, meta)
    except Exception as e:  # the call would stay silent: a fail
        result = {"answer": "", "confidence": 0.0, "needs_expert": False, "topic": ""}
        meta = {"path": "error", "tools": [], "refs": []}
        fails = [f"error: {e!r}"[:200]]
    return {
        "id": case["id"],
        "kind": case.get("kind", ""),
        "ok": not fails,
        "answer": result["answer"],
        "tools": meta.get("tools") or [],
        "path": meta.get("path"),
        "refs": meta.get("refs") or [],
        "latency_ms": int((time.monotonic() - t0) * 1000),
        "fails": fails,
    }


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def markdown(rows: list[dict], cases: dict[str, dict]) -> str:
    passed = sum(r["ok"] for r in rows)
    model = get_settings().OPENAI_CHAT_MODEL
    out = [
        "# MSP demo eval (INC-024, profile msp)",
        "",
        "Generated by `cd backend && uv run python ../scripts/eval_msp.py` "
        f"(model `{model}`, brief = INC-024 ticket, empty transcript, same answer path as a "
        "call). Questions: `backend/seed/msp/eval.json`.",
        "",
        f"**Total: {passed}/{len(rows)} passed.**",
        "",
        "| id | kind | pass | latency | path / tools | question | answer | citations | failures |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        tools = f"{r['path']}: {', '.join(r['tools']) or '-'}"
        out.append(
            "| "
            + " | ".join(
                _cell(x)
                for x in (
                    r["id"],
                    r["kind"],
                    "PASS" if r["ok"] else "FAIL",
                    f"{r['latency_ms'] / 1000:.1f} s",
                    tools,
                    cases[r["id"]]["question"],
                    r["answer"] or "(silent)",
                    "<br>".join(r["refs"]) or "-",
                    "; ".join(r["fails"]) or "-",
                )
            )
            + " |"
        )
    return "\n".join(out) + "\n"


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", help="comma-separated case ids, e.g. T3,T7")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    s = get_settings()
    if not (s.OPENAI_API_KEY and s.OPENAI_CHAT_MODEL):
        print("OPENAI_API_KEY and OPENAI_CHAT_MODEL are required", file=sys.stderr)
        return 2
    # memory-only overrides: runtime.save would write the DB setting of a running backend
    runtime._overrides["DEMO_PROFILE"] = "msp"  # noqa: SLF001
    runtime._overrides["AGENT_TOOLS"] = "true"  # noqa: SLF001
    profile.reset()
    brief = profile.default_brief() or ""
    cases = json.loads(EVAL.read_text(encoding="utf-8"))
    if args.only:
        wanted = {x.strip() for x in args.only.split(",")}
        cases = [c for c in cases if c["id"] in wanted]
    rows = []
    for case in cases:
        r = await run_case(case, brief)
        rows.append(r)
        mark = "PASS" if r["ok"] else "FAIL"
        print(f"{r['id']:>4} {mark} {r['latency_ms'] / 1000:5.1f}s [{','.join(r['tools'])}]")
        print(f"      A: {r['answer']}")
        for ref in r["refs"][:3]:
            print(f"      cite: {ref}")
        for f in r["fails"]:
            print(f"      x {f}")
    passed = sum(r["ok"] for r in rows)
    print(f"\nTotal: {passed}/{len(rows)}")
    Path(args.out).write_text(markdown(rows, {c["id"]: c for c in cases}), encoding="utf-8")
    print(f"wrote {args.out}")
    from app import llm

    await llm.close()
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
